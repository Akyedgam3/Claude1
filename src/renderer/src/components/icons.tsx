export type IconName = keyof typeof ICONS;
/** للاختبارات: الأيقونات المعرّفة */
export const ICON_NAMES = Object.keys(ICONS);

/** أيقونة خطية موحّدة بدل الرموز التعبيرية. */
export function Icon({ name, size = 18, className, title }: { name: string; size?: number; className?: string; title?: string }) {
  const C = ICONS[name] ?? Package;
  return <C size={size} strokeWidth={1.9} className={`icon-svg ${className ?? ''}`} aria-hidden={title ? undefined : true} {...(title ? { 'aria-label': title } : {})} />;
}

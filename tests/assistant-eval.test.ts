describe('assistant evaluation', () => {
  it('answers real customer questions with the right topic (≥ 97%)', () => {
    const brain = new Brain(TOPICS);
    const misses: string[] = [];
    for (const [q, id] of EVAL) {
      const r = brain.search(q, 3);
      if (r[0]?.topic.id !== id) misses.push(`${q} ← ${id} | فهم: ${r.map((x) => `${x.topic.id}(${x.score.toFixed(1)})`).join(' ')}`);
    }
    if (misses.length) console.log(misses.join('\n'));
    const acc = 1 - misses.length / EVAL.length;
    console.log(`دقة المساعد: ${(acc * 100).toFixed(1)}% (${EVAL.length - misses.length}/${EVAL.length})`);
    expect(acc).toBeGreaterThanOrEqual(0.97);
    // والجواب الصح بين أول تلات اقتراحات (المساعد بيعرضهن أزرار) دايماً تقريباً
    const top3 = EVAL.filter(([q, id]) => brain.search(q, 3).some((x) => x.topic.id === id)).length / EVAL.length;
    expect(top3).toBeGreaterThanOrEqual(0.99);
  });
});

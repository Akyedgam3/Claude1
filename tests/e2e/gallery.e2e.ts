import fs from 'node:fs';
import path from 'node:path';
import { test, type Page } from '@playwright/test';
import { activate, companyWizard, launch, nav } from './helpers';

test.setTimeout(60 * 60 * 1000);
const OUT = process.env.GALLERY_OUT!;
type Shot = { title: string; desc: string; go?: string; run?: (p: Page) => Promise<unknown>; el?: string };
const captions: Record<string, { title: string; desc: string; act: string }> = fs.existsSync(path.join(OUT, 'captions.json')) ? JSON.parse(fs.readFileSync(path.join(OUT, 'captions.json'), 'utf8')) : {};
let n = Object.keys(captions).length;

const click = (p: Page, sel: string, hasText?: string | RegExp) => p.locator(sel, hasText ? { hasText } : {}).first().click({ timeout: 5000 });
const tab = (p: Page, name: string | RegExp) => p.getByRole('button', { name }).first().click({ timeout: 5000 });
const scroll = (p: Page, y: number) => p.evaluate((yy) => { for (const el of document.querySelectorAll('main, .content, .main')) (el as HTMLElement).scrollTo(0, yy); }, y);

async function company(activity: string, name: string, shots: Shot[]) {
  const { page, close } = await launch();
  try {
    await activate(page);
    await companyWizard(page, { activity, name, owner: 'المالك', username: 'admin', demo: true });
    await page.getByRole('button', { name: 'حفظته، تابع' }).click();
    await page.waitForTimeout(1200);
    for (const s of shots) {
      try {
        await page.keyboard.press('Escape').catch(() => undefined);
        if (s.go) await nav(page, s.go);
        await page.waitForTimeout(700);
        if (s.run) await s.run(page);
        await page.waitForTimeout(800);
        const id = String(++n).padStart(3, '0');
        const file = path.join(OUT, 'raw', `${id}.png`);
        if (s.el) await page.locator(s.el).first().screenshot({ path: file });
        else await page.screenshot({ path: file });
        captions[id] = { title: s.title, desc: s.desc, act: activity };
        fs.writeFileSync(path.join(OUT, 'captions.json'), JSON.stringify(captions, null, 1));
        console.log('SHOT', id, s.title);
      } catch (e) {
        console.log('SKIP', s.title, String(e).slice(0, 160));
      }
    }
  } finally {
    await close();
  }
}

